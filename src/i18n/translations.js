export function projectText(t, project) {
  if (!project) return { description: '', category: '' }
  const copy = t.projects?.[String(project.id)]
  return {
    description: copy?.description || project.description || '',
    category: t.projectCategories?.[project.category] || project.category || '',
  }
}

